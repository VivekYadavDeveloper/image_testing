import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:google_fonts/google_fonts.dart';

import 'core/constants.dart';
import 'cubit/images/images_cubit.dart';
import 'cubit/upload/upload_cubit.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'repositories/image_repository.dart';
import 'screens/main_shell.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return RepositoryProvider(
      create: (_) => ImageRepository(),
      child: MultiBlocProvider(
        providers: [
          BlocProvider(create: (c) => UploadCubit(c.read<ImageRepository>())),
          BlocProvider(create: (c) => ImagesCubit(c.read<ImageRepository>())),
        ],
        child: MaterialApp(
          debugShowCheckedModeBanner: false,
          title: 'Image App',
          theme: ThemeData(
            useMaterial3: true,
            colorSchemeSeed: AppColors.green,
            scaffoldBackgroundColor: Colors.white,
            textTheme: GoogleFonts.montserratTextTheme(),
          ),
          home: const MainShell(),
        ),
      ),
    );
  }
}
